"""Emit the one reviewed NETGEAR WDS instruction overlay for the native loader."""

import argparse
import hashlib
from pathlib import Path


IMAGE_SIZE = 0x180000
ORIGINAL_SHA256 = "6801144d7d45d66ffdb867624d4906a6f215243cd00fa9d1611333ddf6477908"
CORRECTED_SHA256 = "58f928980c996b10e334e0c35d582ce12c1a8423dbc8f57cd9815ed0c3d7d875"

# Fixed output sections of rax40-wds.ld; not a general firmware patch format.
SECTIONS = (
    ("ba_owner", 0x4BB54, 140),
    ("default_owner", 0x4D0C8, 56),
    ("key_commit_hook", 0x4D25E, 4),
    ("keyslot_owner", 0x4D264, 130),
    ("hif", 0x5A88C, 632),
    ("lmac1", 0xF377C, 100),
    ("sta1_hook", 0xFE25A, 4),
    ("lmac2", 0x143424, 100),
    ("sta2_hook", 0x14DF0E, 4),
)

# Only changed code and the adjacent original bytes required by DWORD writes.
SPANS = (
    (0x4BB54, 140),
    (0x4D0C8, 56),
    (0x4D25C, 140),
    (0x5A8A0, 4),
    (0x5A9E8, 4),
    (0x5AA68, 156),
    (0xF377C, 100),
    (0xFE258, 8),
    (0x143424, 100),
    (0x14DF0C, 8),
)


def bytes_as_c(data):
    return "\n".join(
        "  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ","
        for i in range(0, len(data), 12)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--original", required=True, type=Path)
    parser.add_argument("--sections", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    original = args.original.read_bytes()
    if len(original) != IMAGE_SIZE or hashlib.sha256(original).hexdigest() != ORIGINAL_SHA256:
        raise SystemExit("Original AP size/SHA256 does not match the selected NETGEAR image")
    corrected = bytearray(original)
    for name, offset, size in SECTIONS:
        data = (args.sections / f"{name}.bin").read_bytes()
        if len(data) != size:
            raise SystemExit(f"Unexpected ARC section size: {name}")
        corrected[offset:offset + size] = data
    if hashlib.sha256(corrected).hexdigest() != CORRECTED_SHA256:
        raise SystemExit("ARC sections do not reproduce the reviewed corrected AP SHA256")

    payload = bytearray()
    rows = []
    reconstructed = bytearray(original)
    for offset, size in SPANS:
        if (offset | size | len(payload)) & 3 or offset + size > IMAGE_SIZE:
            raise SystemExit("Invalid native DWORD overlay extent")
        rows.append(f"  {{ 0x{offset:08x}, {len(payload)}, {size} }},")
        data = corrected[offset:offset + size]
        payload.extend(data)
        reconstructed[offset:offset + size] = data
    if len(payload) != 716 or reconstructed != corrected:
        raise SystemExit("Native loader spans do not reproduce the complete reviewed image")

    header = f"""/* Firmware instruction data for the pinned NETGEAR RAX40 image.
 * Original firmware licensing applies; no additional permission is granted here.
 */
/* Generated by firmware/generate-loader-data.py; do not edit.
 * Original AP SHA256: {ORIGINAL_SHA256}
 * Reviewed corrected AP SHA256: {CORRECTED_SHA256}
 */
#ifndef WAVE_WDS_AP_IMAGE_H
#define WAVE_WDS_AP_IMAGE_H

#define WAVE_WDS_AP_SIZE 0x00180000u

static const uint8 wave_wds_ap_original_sha256[32] = {{
{bytes_as_c(bytes.fromhex(ORIGINAL_SHA256))}
}};

/* Preserve byte order through the native swap=FALSE raw-DWORD writer. */
static const uint8 wave_wds_ap_code[716] __aligned(4) = {{
{bytes_as_c(payload)}
}};

static const struct wave_wds_ap_span {{
  uint32 offset;
  uint16 data_offset;
  uint16 size;
}} wave_wds_ap_spans[] = {{
{chr(10).join(rows)}
}};

#endif /* WAVE_WDS_AP_IMAGE_H */
"""
    args.output.write_text(header)
    print(f"{args.output}: {len(SPANS)} DWORD spans, {len(payload)} bytes, "
          f"corrected AP {CORRECTED_SHA256}")


if __name__ == "__main__":
    main()
